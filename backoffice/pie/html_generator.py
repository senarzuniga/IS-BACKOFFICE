def _build_nav(analysis: PresentationAnalysis) -> str:
    items = []
    for slide in analysis.slides:
        title = html.escape(slide.title or f"Slide {slide.index}")
        items.append(f"<a href='#slide-{slide.index}' class='toc-item' data-target='slide-{slide.index}'>{slide.index}. {title}</a>")
    return "\n".join(items)


def _build_summary(analysis: PresentationAnalysis) -> str:
    palette = " ".join(f"<span class='chip'>{html.escape(c)}</span>" for c in analysis.global_palette[:8])
    return f"""
<section class=\"section-card\" id=\"executive-summary\">
  <h2>Executive Summary</h2>
  <p>Presentation Intelligence Engine converted <strong>{analysis.slide_count}</strong> slides into reusable HTML components with responsive behavior.</p>
  <div class=\"kpis\">
    <div class=\"kpi\"><span>Slides</span><strong>{analysis.slide_count}</strong></div>
    <div class=\"kpi\"><span>Palette Colors</span><strong>{len(analysis.global_palette)}</strong></div>
    <div class=\"kpi\"><span>Typography Families</span><strong>{len(analysis.typography.get('font_usage', {}))}</strong></div>
  </div>
  <div class=\"chips\">{palette}</div>
</section>
"""


def _render_slide_section(slide: SlideAnalysis, mode: str) -> str:
    blocks = []
    blocks.append(f"<div class='breadcrumb'>Home / Chapter {slide.index} / {html.escape(slide.title)}</div>")
    blocks.append(f"<h2>{html.escape(slide.title or f'Slide {slide.index}')}</h2>")

    if mode == "flow":
        for el in slide.elements:
            blocks.append(_render_element_flow(el))
    else:
        grouped = _group_elements_for_smart(slide.elements)
        for gname, items in grouped.items():
            blocks.append(f"<h3>{html.escape(gname)}</h3>")
            blocks.append("<div class='grid'>")
            for item in items:
                blocks.append(_render_element_smart(item))
            blocks.append("</div>")

    return f"""
<section class=\"section-card slide\" id=\"slide-{slide.index}\" data-title=\"{html.escape(slide.title)}\">
  {''.join(blocks)}
</section>
"""


def _render_element_flow(el: SlideElement) -> str:
    if el.kind in {"title", "heading", "text", "smartart"}:
        cls = "title" if el.kind == "title" else "text"
        content = _paragraphs(el.text)
        return f"<article class='element {cls}'>{content}</article>"
    if el.kind == "image" and el.asset_path:
        return f"<figure class='element image'><img src='{html.escape(el.asset_path)}' loading='lazy' alt='slide visual' /></figure>"
    if el.kind == "table":
        return _render_table(el.table_rows)
    if el.kind == "chart":
        return _render_chart_svg(el.chart)
    return ""


def _render_element_smart(el: SlideElement) -> str:
    if el.kind in {"title", "heading", "text", "smartart"}:
        return f"<article class='card'><p>{_escape_and_trim(el.text, 400)}</p></article>"
    if el.kind == "image" and el.asset_path:
        return f"<article class='card image'><img src='{html.escape(el.asset_path)}' loading='lazy' alt='component image' /></article>"
    if el.kind == "table":
        return f"<article class='card'>{_render_table(el.table_rows)}</article>"
    if el.kind == "chart":
        return f"<article class='card'>{_render_chart_svg(el.chart)}</article>"
    return ""


def _group_elements_for_smart(elements: list[SlideElement]) -> dict[str, list[SlideElement]]:
    groups = {
        "Narrative": [],
        "Cards and Lists": [],
        "Data Tables": [],
        "Charts and Diagrams": [],
        "Visual Assets": [],
    }
    for el in elements:
        if el.kind in {"title", "heading", "text"}:
            if "\n" in el.text or "- " in el.text:
                groups["Cards and Lists"].append(el)
            else:
                groups["Narrative"].append(el)
        elif el.kind == "table":
            groups["Data Tables"].append(el)
        elif el.kind in {"chart", "smartart"}:
            groups["Charts and Diagrams"].append(el)
        elif el.kind == "image":
            groups["Visual Assets"].append(el)

    return {k: v for k, v in groups.items() if v}


def _render_table(rows: list[list[str]]) -> str:
    if not rows:
        return ""
    head = rows[0]
    body = rows[1:] if len(rows) > 1 else []
    th = "".join(f"<th>{html.escape(c)}</th>" for c in head)
    tr = "".join("<tr>" + "".join(f"<td>{html.escape(c)}</td>" for c in row) + "</tr>" for row in body)
    csv_payload = json.dumps(rows)
    return f"""
<div class='table-tools'>
  <button type='button' class='btn tiny' onclick='pieSortTable(this)'>Sort</button>
  <button type='button' class='btn tiny' onclick='pieExportTable(this, {csv_payload})'>Export CSV</button>
</div>
<div class='table-wrap'><table><thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table></div>
"""


def _render_chart_svg(chart: dict[str, Any]) -> str:
    series = chart.get("series") or []
    if not series or not isinstance(series, list):
        return "<div class='chart-empty'>Chart metadata detected but values were not available.</div>"

    values = [float(v or 0) for v in series[0].get("values", [])]
    if not values:
        return "<div class='chart-empty'>Chart values unavailable.</div>"

    max_val = max(values) or 1.0
    bars = []
    width = 520
    height = 220
    pad = 24
    bw = max((width - pad * 2) / max(len(values), 1) - 8, 8)
    for idx, val in enumerate(values):
        x = pad + idx * (bw + 8)
        h = int((val / max_val) * (height - 60))
        y = height - h - 20
        bars.append(f"<rect x='{x:.1f}' y='{y}' width='{bw:.1f}' height='{h}' rx='4'></rect>")

    return f"""
<svg class='chart' viewBox='0 0 {width} {height}' role='img' aria-label='Reconstructed chart'>
  <line x1='20' y1='{height-20}' x2='{width-20}' y2='{height-20}'></line>
  {''.join(bars)}
</svg>
"""


def _paragraphs(text: str) -> str:
    parts = [p.strip() for p in text.split("\n") if p.strip()]
    if not parts:
        return ""
    if len(parts) == 1:
        return f"<p>{html.escape(parts[0])}</p>"
    return "".join(f"<p>{html.escape(p)}</p>" for p in parts)


def _escape_and_trim(text: str, max_len: int) -> str:
    safe = html.escape(text.strip())
    if len(safe) <= max_len:
        return safe
    return safe[: max_len - 1] + "..."


