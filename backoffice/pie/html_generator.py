def _ui_scripts() -> str:
    return """
<script>
const sections = Array.from(document.querySelectorAll('.slide'));
const tocLinks = Array.from(document.querySelectorAll('.toc-item'));

function updateActiveToc() {
  let active = null;
  for (const sec of sections) {
    const rect = sec.getBoundingClientRect();
    if (rect.top <= 180 && rect.bottom >= 180) {
      active = sec.id;
      break;
    }
  }
  tocLinks.forEach((a) => a.classList.toggle('active', a.dataset.target === active));
}

function updateProgress() {
  const total = document.body.scrollHeight - window.innerHeight;
  const pct = total > 0 ? (window.scrollY / total) * 100 : 0;
  document.getElementById('progress').style.width = pct.toFixed(1) + '%';
}

function toggleTheme() {
  const root = document.documentElement;
  root.dataset.theme = root.dataset.theme === 'dark' ? 'light' : 'dark';
}

function togglePresentation() {
  document.body.classList.toggle('presentation');
}

function toggleSnap() {
  const sectionsWrap = document.querySelector('.sections');
  if (!sectionsWrap) return;
  const current = sectionsWrap.getAttribute('data-scroll-snap');
  sectionsWrap.setAttribute('data-scroll-snap', current === 'on' ? 'off' : 'on');
}

function toggleFullScreen() {
  if (!document.fullscreenElement) {
    document.documentElement.requestFullscreen();
  } else {
    document.exitFullscreen();
  }
}

function pieSortTable(button) {
  const table = button.parentElement.nextElementSibling.querySelector('table');
  if (!table) return;
  const rows = Array.from(table.tBodies[0].rows);
  const asc = !table.dataset.asc || table.dataset.asc === '0';
  rows.sort((a,b) => {
    const x = a.cells[0].innerText.trim();
    const y = b.cells[0].innerText.trim();
    return asc ? x.localeCompare(y, undefined, {numeric:true}) : y.localeCompare(x, undefined, {numeric:true});
  });
  table.dataset.asc = asc ? '1' : '0';
  rows.forEach(r => table.tBodies[0].appendChild(r));
}

function pieExportTable(button, rows) {
  const csv = rows.map(r => r.map(cell => '"' + String(cell).replaceAll('"', '""') + '"').join(',')).join('\n');
  const blob = new Blob([csv], {type: 'text/csv'});
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = 'table_export.csv';
  a.click();
  URL.revokeObjectURL(a.href);
}

function runAiCommand() {
  const input = document.getElementById('aiInput');
  const log = document.getElementById('aiLog');
  const command = (input.value || '').trim().toLowerCase();
  if (!command) return;

  if (command.includes('reduce text') || command.includes('reduce')) {
    document.querySelectorAll('p').forEach((p) => {
      if (p.innerText.length > 280) p.innerText = p.innerText.slice(0, 280) + '...';
    });
    log.innerText += '\n- Mission Manager: Text reduction applied.';
  } else if (command.includes('cards')) {
    document.querySelectorAll('.element.text').forEach((el) => el.classList.add('card'));
    log.innerText += '\n- Mission Manager: Converted text blocks into card styling.';
  } else if (command.includes('animations') || command.includes('visual')) {
    document.querySelectorAll('.section-card').forEach((el, i) => {
      el.style.animation = `fadeIn 350ms ease ${i * 50}ms both`;
    });
    log.innerText += '\n- Mission Manager: Visual animation profile enabled.';
  } else if (command.includes('translate')) {
    log.innerText += '\n- Mission Manager: Translation request captured (hook for server-side pipeline).';
  } else {
    log.innerText += '\n- Mission Manager: Command captured, no direct local transform mapped.';
  }

  input.value = '';
}

window.addEventListener('scroll', () => { updateProgress(); updateActiveToc(); });
window.addEventListener('load', () => { updateProgress(); updateActiveToc(); });
</script>
<style>@keyframes fadeIn { from {opacity:0; transform: translateY(8px);} to {opacity:1; transform: translateY(0);} }</style>
"""
